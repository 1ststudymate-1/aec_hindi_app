"""प्रश्न-बैंक : MCQ (अभ्यास), very short (Group A) और descriptive (Group B) प्रश्न."""

MCQS: list[dict] = []
SHORTS: list[dict] = []
DESCRIPTIVES: list[dict] = []


def _mcq(unit: int, topic_slug: str, n: int, question: str, options: list[str], ai: int, expl: str) -> None:
    MCQS.append({
        "id": f"mcq-{topic_slug}-{n}",
        "qtype": "mcq",
        "topic_slug": topic_slug,
        "unit": unit,
        "question": question,
        "options": options,
        "answer_index": ai,
        "explanation": expl,
        "answer": None,
        "marks": 1,
    })


def _short(unit: int, topic_slug: str, n: int, question: str, answer: str) -> None:
    SHORTS.append({
        "id": f"short-{topic_slug}-{n}",
        "qtype": "short",
        "topic_slug": topic_slug,
        "unit": unit,
        "question": question,
        "options": None,
        "answer_index": None,
        "explanation": None,
        "answer": answer,
        "marks": 1,
    })


def _desc(unit: int, topic_slug: str, n: int, question: str, answer: str) -> None:
    DESCRIPTIVES.append({
        "id": f"desc-{topic_slug}-{n}",
        "qtype": "descriptive",
        "topic_slug": topic_slug,
        "unit": unit,
        "question": question,
        "options": None,
        "answer_index": None,
        "explanation": None,
        "answer": answer,
        "marks": 15,
    })


