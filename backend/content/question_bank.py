def model_answer(topic):
    parts = []
    for section in topic["sections"]:
        if section["heading"] in ("लेखन अभ्यास", "स्वयं अभ्यास करें"):
            continue
        parts.append(section["heading"])
        for block in section["blocks"]:
            if block.get("text"):
                parts.append(block["text"])
            for item in block.get("items", []):
                parts.append("• " + item)
            # Representative examples plus all distinct samas/sandhi categories are explained above.
            for row in block.get("rows", [])[:12]:
                parts.append(" — ".join(row))
        parts.append("")
    return "मॉडल उत्तर (अभ्यास हेतु; शब्द-सीमा प्रश्नानुसार रखें)\n\n" + "\n".join(parts)


