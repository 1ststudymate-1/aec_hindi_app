def mcq(slug, question, right, wrong, explanation, unit=2):
    n = 1 + sum(q["topic_slug"] == slug for q in MCQS)
    # Vary the correct position, without randomness or duplicate choices.
    options = list(dict.fromkeys(x for x in wrong if x != right))[:3]
    assert len(options) == 3
    index = (n - 1) % 4
    options.insert(index, right)
    MCQS.append({"id": f"mcq-{slug}-{n}", "qtype": "mcq", "topic_slug": slug, "unit": unit,
        "question": question, "options": options, "answer_index": index, "explanation": explanation,
        "answer": None, "marks": 1})


